#!/usr/bin/env python3
"""Render the canonical SVG into native tray assets (macOS + Command Line Tools).

No third-party Python modules. Generated files are checked in, so ordinary app
builds do not need Python or this renderer. Only the SVG path/rotation subset used
by our icon is supported; unsupported commands fail rather than silently drift.
"""
import math
from pathlib import Path
import re
import struct
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / 'assets'
svg = ET.parse(ASSETS / 'tray-icon.svg').getroot()

def number(value):
    return f'{float(value):.6f}'.rstrip('0').rstrip('.') or '0'

def path_commands(data):
    tokens = re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?', data)
    out, x, y, i = [], 0., 0., 0
    while i < len(tokens):
        command = tokens[i]
        i += 1
        counts = {'M': 2, 'L': 2, 'H': 1, 'V': 1, 'C': 6, 'Z': 0}
        if command not in counts:
            raise ValueError(f'Unsupported SVG command: {command}')
        count = counts[command]
        values = [float(v) for v in tokens[i:i + count]]
        i += count
        if command in ('M', 'L'):
            x, y = values
            out.append(f'{number(x)} {number(y)} {"m" if command == "M" else "l"}')
        elif command in ('H', 'V'):
            if command == 'H': x = values[0]
            else: y = values[0]
            out.append(f'{number(x)} {number(y)} l')
        elif command == 'C':
            x, y = values[-2:]
            out.append(' '.join(map(number, values)) + ' c')
        else:
            out.append('h')
    return '\n'.join(out)

def draw(element):
    tag = element.tag.rsplit('}', 1)[-1]
    if tag in ('title', 'desc'):
        return ''
    out = ['q']
    if transform := element.get('transform'):
        match = re.fullmatch(r'rotate\(([-\d.]+) ([-\d.]+) ([-\d.]+)\)', transform)
        if not match:
            raise ValueError(f'Unsupported SVG transform: {transform}')
        angle, cx, cy = map(float, match.groups())
        c, s = math.cos(math.radians(angle)), math.sin(math.radians(angle))
        out.append(' '.join(map(number, (c, s, -s, c, cx - c * cx + s * cy, cy - s * cx - c * cy))) + ' cm')
    if tag == 'path':
        out.extend((path_commands(element.attrib['d']), 'S'))
    elif tag not in ('g', 'svg'):
        raise ValueError(f'Unsupported SVG element: {tag}')
    out.extend(draw(child) for child in element)
    out.append('Q')
    return '\n'.join(out)

stream = ('q\n1 0 0 -1 0 24 cm\n0 0 0 RG\n' + svg.attrib['stroke-width'] + ' w\n1 J\n1 j\n' + draw(svg) + '\nQ\n').encode('ascii')
objects = [b'<< /Type /Catalog /Pages 2 0 R >>',
           b'<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
           b'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 24 24] /Resources << >> /Contents 4 0 R >>',
           b'<< /Length ' + str(len(stream)).encode() + b' >>\nstream\n' + stream + b'endstream']
pdf = bytearray(b'%PDF-1.4\n')
offsets = [0]
for index, obj in enumerate(objects, 1):
    offsets.append(len(pdf))
    pdf.extend(f'{index} 0 obj\n'.encode() + obj + b'\nendobj\n')
xref = len(pdf)
pdf.extend(f'xref\n0 {len(offsets)}\n0000000000 65535 f \n'.encode())
for offset in offsets[1:]:
    pdf.extend(f'{offset:010d} 00000 n \n'.encode())
pdf.extend(f'trailer\n<< /Size {len(offsets)} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n'.encode())
(ASSETS / 'tray-icon.pdf').write_bytes(pdf)
header = '// Generated by scripts/generate_tray_icons.py from assets/tray-icon.svg.\nstatic const unsigned char cs_tray_icon_pdf[] = {\n'
for i in range(0, len(pdf), 16):
    header += '    ' + ', '.join(f'0x{b:02x}' for b in pdf[i:i + 16]) + ',\n'
(ASSETS / 'tray_icon_pdf.h').write_text(header + '};\n')

with tempfile.TemporaryDirectory(prefix='clipboard-icon-') as tmp:
    tmp = Path(tmp)
    renderer = tmp / 'render'
    subprocess.run(['xcrun', 'clang', '-fobjc-arc', '-framework', 'AppKit', str(ROOT / 'scripts/render_tray_icon.m'), '-o', str(renderer)], check=True)
    subprocess.run([str(renderer), str(ASSETS / 'tray-icon.pdf'), str(tmp)], check=True)
    sizes = (16, 20, 24, 32, 40, 48, 64, 256)
    for color in ('black', 'white'):
        chunks = [(tmp / f'{color}-{n}.png').read_bytes() for n in sizes]
        ico = bytearray(struct.pack('<HHH', 0, 1, len(sizes)))
        offset = 6 + 16 * len(sizes)
        for size, chunk in zip(sizes, chunks):
            ico.extend(struct.pack('<BBBBHHII', size % 256, size % 256, 0, 0, 1, 32, len(chunk), offset))
            offset += len(chunk)
        ico.extend(b''.join(chunks))
        (ASSETS / f'tray-{color}.ico').write_bytes(ico)
    (ASSETS / 'tray-icon-preview.png').write_bytes((tmp / 'preview.png').read_bytes())
    iconset = tmp / 'AppIcon.iconset'
    iconset.mkdir()
    for points in (16, 32, 128, 256, 512):
        for factor in (1, 2):
            suffix = '@2x' if factor == 2 else ''
            shutil.copyfile(tmp / f'app-{points * factor}.png', iconset / f'icon_{points}x{points}{suffix}.png')
    subprocess.run(['iconutil', '-c', 'icns', str(iconset), '-o', str(ASSETS / 'AppIcon.icns')], check=True)
    shutil.copyfile(tmp / 'app-256.png', ASSETS / 'app-icon-preview.png')
print('Generated PDF template, embedded header, multi-resolution ICOs, macOS application icon and previews.')
